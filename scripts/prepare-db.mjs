import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const sources = [
  "supabase/migrations/202610260001_initial_schema.sql",
  "supabase/migrations/202610260002_private_storage.sql",
  "supabase/migrations/202610260003_workflow_api.sql",
  "supabase/migrations/202610270004_care_workflows.sql",
  "supabase/migrations/202610280005_patient_journey.sql",
  "supabase/seed.sql",
];
const sections = [];
for (const source of sources) {
  let sql = (await readFile(new URL(source, root), "utf8"))
    .replace(/\r\n/g, "\n")
    .trim();
  if (source.includes("/migrations/")) {
    // Each source wraps its statements in one outer transaction. Combine them
    // into one transaction so a failed first-time setup cannot apply partially.
    if (
      (sql.match(/^begin;$/gm) || []).length !== 1 ||
      (sql.match(/^commit;$/gm) || []).length !== 1
    ) {
      throw new Error(`Unexpected transaction structure: ${source}`);
    }
    sql = sql
      .replace(/^begin;\n?/m, "")
      .replace(/^commit;$/m, "")
      .trim();
  }
  sections.push(`-- Source: ${source}\n${sql}`);
}
const output = `-- Aarogya Drishti: FIRST-TIME Supabase setup.
-- Generated by npm run db:prepare. Edit source migrations, not this file.
-- Paste this WHOLE file into Supabase SQL Editor and run as postgres.
-- Includes five migrations and three synthetic facilities; creates no users.
-- Run only once on a project without this application's schema.
-- After this succeeds, create the five Auth users and run demo_seed.sql.
begin;
do $$ begin
  if exists(select 1 from pg_namespace where nspname = 'app_private') then
    raise exception 'Application schema already exists. Apply only missing migrations; do not re-run first-time setup.';
  end if;
end $$;

${sections.join("\n\n")}

notify pgrst, 'reload schema';
commit;

-- Expected result: 20 application tables, each with rowsecurity = true.
select tablename, rowsecurity from pg_tables
where schemaname = 'public' order by tablename;
`;
await writeFile(new URL("supabase/setup.sql", root), output, "utf8");
console.log(
  "Prepared supabase/setup.sql: five migrations and facility seed, in one transaction.",
);
